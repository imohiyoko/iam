// Command pgport は SQLite アダプタのクエリと Repository の実装から、PostgreSQL アダプタのものを作る（ADR 0067）。
// 2つのアダプタの SQL と Go のコードを同じに保つため、PostgreSQL の側は手で直さず、これで作り直す（CI で差分を確かめる）。
// マイグレーションは別（PostgreSQL の側に手で足す）。
//
//	cd adapters/storage/postgres && go run ./cmd/pgport && sqlc generate
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const (
	src = "../sqlite"
	dst = "."
)

// glue は Repository の実装（SQLite に依らないファイル）。
var glue = []string{"authn.go", "authz.go", "oidc.go", "org.go", "passkey.go", "password.go", "recovery.go", "suspension.go", "totp.go"}

var (
	blockRE   = regexp.MustCompile(`(?m)^-- name:`)
	limitRE   = regexp.MustCompile(`LIMIT \?`)
	posRE     = regexp.MustCompile(`\?`)
	namedRE   = regexp.MustCompile(`(([\w.]+) (?:=|<>|>=|<=|>|<) )\$\d+`)
	dollarRE  = regexp.MustCompile(`\$\d`)
	limCastRE = regexp.MustCompile(`sqlc\.arg\((lim|'limit')\)`)
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "pgport:", err)
		os.Exit(1)
	}
}

func run() error {
	qs, err := filepath.Glob(filepath.Join(src, "queries", "*.sql"))
	if err != nil {
		return err
	}
	for _, f := range qs {
		b, err := os.ReadFile(f) // #nosec G304 -- リポジトリ内のファイル
		if err != nil {
			return err
		}
		out := header("--") + convertQueries(string(b))
		if err := os.WriteFile(filepath.Join(dst, "queries", filepath.Base(f)), []byte(out), 0o600); err != nil { // #nosec G703 -- リポジトリ内のファイル名
			return err
		}
	}
	for _, f := range glue {
		b, err := os.ReadFile(filepath.Join(src, f)) // #nosec G304 -- リポジトリ内のファイル
		if err != nil {
			return err
		}
		s := string(b)
		s = strings.Replace(s, "package sqlite", "package postgres", 1)
		s = strings.ReplaceAll(s, `"github.com/imohiyoko/iam/adapters/storage/sqlite/db"`, `"github.com/imohiyoko/iam/adapters/storage/postgres/db"`)
		s = strings.ReplaceAll(s, `"sqlite: `, `"postgres: `)
		if err := os.WriteFile(filepath.Join(dst, f), []byte(header("//")+s), 0o600); err != nil { // #nosec G703 -- 決まったファイル名
			return err
		}
	}
	return nil
}

func header(comment string) string {
	return comment + " Code generated by cmd/pgport from adapters/storage/sqlite. DO NOT EDIT.\n\n"
}

// convertQueries は SQLite のクエリを PostgreSQL のものにする。
//   - ? は $1, $2, ...。名前つきの引数（sqlc.arg）と混ぜられないので、混ざるクエリでは比べる列の名前の sqlc.arg にする
//   - LIMIT の引数は bigint（SQLite と同じ int64 にする）
//   - max(a, b) は GREATEST、rowid は ord
func convertQueries(s string) string {
	idx := blockRE.FindAllStringIndex(s, -1)
	var b strings.Builder
	prev := 0
	for _, loc := range idx {
		b.WriteString(convertQuery(s[prev:loc[0]]))
		prev = loc[0]
	}
	b.WriteString(convertQuery(s[prev:]))
	return b.String()
}

func convertQuery(q string) string {
	q = limitRE.ReplaceAllString(q, "LIMIT sqlc.arg('limit')")
	n := 0
	q = posRE.ReplaceAllStringFunc(q, func(string) string { n++; return fmt.Sprintf("$%d", n) })
	if strings.Contains(q, "sqlc.arg") && dollarRE.MatchString(q) {
		q = namedRE.ReplaceAllStringFunc(q, func(m string) string {
			sub := namedRE.FindStringSubmatch(m)
			col := sub[2][strings.LastIndex(sub[2], ".")+1:]
			return sub[1] + "sqlc.arg(" + col + ")"
		})
	}
	q = limCastRE.ReplaceAllString(q, "sqlc.arg($1)::bigint")
	q = strings.ReplaceAll(q, "max(last_seen_at, sqlc.arg(at))", "GREATEST(last_seen_at, sqlc.arg(at))")
	q = strings.ReplaceAll(q, "ORDER BY created_at, rowid", "ORDER BY created_at, ord")
	return q
}
